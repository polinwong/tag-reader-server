func TestECBEncrypt(t *testing.T) {
	ret := e([]byte(ecbKey), []byte(ecbData))
	t.Logf("encrypted: %s", hex.EncodeToString(ret))

	raw := PKCS7UnPadding(d([]byte(ecbKey), ret))
	if fin := string(raw); fin == ecbData {
		t.Logf("result: %s", fin)
	} else {
		t.Fail()
	}
}

func TestGenerate(t *testing.T) {
	testData := func(k testSet) {
		b, err := hex.DecodeString(k.key)
		if err != nil {
			t.Logf("failed, %s", err)
			t.FailNow()
		}
		lrp := NewLRPString(b, k.uKey, k.iv, false)
		t.Logf("result p: %s", hex.EncodeToString(lrp.p[0]))
		if k.key == setlist[0].key {
			result, _ := hex.DecodeString("71b444af257a93215311d758dd333247")
			if !bytes.Equal(lrp.p[15], result) {
				t.Fail()
			}
		}

		t.Logf("result ku: %s", hex.EncodeToString(lrp.ku[0]))
		if k.key == setlist[0].key {
			result, _ := hex.DecodeString("fe30ab50467e61783bfe6b5e0560160e")
			if !bytes.Equal(lrp.ku[2], result) {
				t.Fail()
			}
		}

		if k.key == setlist[3].key {
			if strings.Compare(k.iv, "1F0B7C0DB12889CA436CABB78BE42F9") != 0 {
				t.Fail()
			}
		}

		y := lrp.evalLRP(lrp.p, lrp.kp, lrp.r, k.final)
		ret := hex.EncodeToString(y)
		log.Printf("y: %s", ret)
		if strings.Compare(ret, strings.ToLower(k.ret)) != 0 {
			t.Fail()
		}
	}

	for _, v := range setlist {
		testData(v)
	}
}

func TestDecrypt(t *testing.T) {
	source := "1fcbe61b3e4cad980cbfdd333e7a4ac4a579569bafd22c5f"
	metakey := "00000000000000000000000000000000"
	retRaw := "c704940e2a2f708003000062e4fcecbf"

	bSource, err := hex.DecodeString(source)
	if err != nil {
		t.FailNow()
	}
	bMetakey, err := hex.DecodeString(metakey)
	if err != nil {
		t.FailNow()
	}
	bRetRaw, _ := hex.DecodeString(retRaw)

	rand := bSource[:8]
	encData := bSource[8:]

	cipher := NewLRP(bMetakey, 0, rand, false)
	ret := cipher.Decrypt(encData)

	if !bytes.Equal(ret, bRetRaw) {
		t.Fail()
	}
}

