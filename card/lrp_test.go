func TestFalseCase(t *testing.T) {
	t.Run(`AESe_dCheck`, func(t *testing.T) {
		falseKey := "0123456789"
		if d := e([]byte(falseKey), []byte(ecbData)); d != nil {
			t.Errorf(`Should failed AES encrypt with invalid data`)
		}

		if d := d([]byte(falseKey), []byte(ecbData)); d != nil {
			t.Errorf(`Should failed AES decrypt with invalid data`)
		}
	})

	t.Run(`nibblesCheck`, func(t *testing.T) {
		if n := nibbles([]byte("0Z"), true); n != nil {
			t.Errorf(`Should nil returned`)
		}
	})

	t.Run(`incrCounterCheck`, func(t *testing.T) {
		if n := incrCounter([]byte{0xf3, 0xf4}); n != nil {
			t.Errorf(`Should failed incrCounter with less data`)
		}
	})

	t.Run(`xorCheck`, func(t *testing.T) {
		if o := xor([]byte{0x0f}, []byte{0x0c, 0x1c}); o != nil {
			t.Errorf(`Should failed xor not same size input`)
		}
	})

	t.Run(`PKCS7UnPaddingCheck`, func(t *testing.T) {
		if o := PKCS7UnPadding([]byte{0x1c, 0x2c, 0x3c, 0x4c, 0x80, 0x00, 0x00, 0x01}); o != nil {
			t.Errorf(`Should failed unpadding with invalid data`)
		}
	})
}
